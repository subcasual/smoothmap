"""Writing patches out as a patch set: YAML written by hand, for readable code blocks and values as
plain as YAML allows."""
from __future__ import annotations

import json
import os
import re
from typing import Any

import yaml

from .patches import Step
from .patches import NO_VALUE, NULL, FieldPatch, MethodPatch, NewMethodPatch, Patch, ValuesPatch, WholeMethodPatch

TITLES = {FieldPatch: "new field", NewMethodPatch: "new method", ValuesPatch: "initial values",
          MethodPatch: "edited ActionScript", WholeMethodPatch: "edited ActionScript (whole method)"}


def patch_set(manifest: dict, patches: list[Patch]) -> str:
    """The patch set: a header naming the source, then each patch with its documentation and ops."""
    classes = ", ".join(name.rpartition(".")[2] for name in manifest["classes"])
    out = [f"# Generated by patch_generator from {os.path.basename(manifest.get('source') or 'a file')} "
           f"(sha256 {manifest['sha256'][:16]}...), classes: {classes}.",
           "# Changed methods are patched where they changed, anchored on the original instructions around each",
           "# change; a method marked (whole method) is replaced whole, anchored on all of its original code.",
           "# Fill in each patch's `why`.",
           "format: 1", "patches:"]
    ids: set[str] = set()
    for patch in patches:
        patch_id = ("add-" if isinstance(patch, (FieldPatch, NewMethodPatch)) else "") + kebab(patch.ref) \
            + ("-initial-values" if isinstance(patch, ValuesPatch) else "")
        while patch_id in ids:
            patch_id += "-x"
        ids.add(patch_id)
        out += [f"  - id: {patch_id}", f"    title: {scalar(f'{patch.ref}: {TITLES[type(patch)]}')}",
                "    why: |", "      TODO: why this change exists."]
        if patch.as3:
            out += ["    as3: |"] + _block(patch.as3.splitlines(), 6)
        out += ["    ops:"] + _ops(patch)
    return "\n".join(out) + "\n"


def _ops(patch: Patch) -> list[str]:
    class_ref, _, member = patch.ref.rpartition(".")
    if isinstance(patch, ValuesPatch):
        out = ["      - set_initial_values:", f"          class: {scalar(patch.ref)}", "          values:"]
        for name, old, new in patch.values:
            entries = ([f"expect: {_flow_value(old)}"] if old is not NO_VALUE else []) + \
                ([f"value: {_flow_value(new)}"] if new is not NO_VALUE else [])
            out.append(f"            {scalar(name)}: {{ {', '.join(entries)} }}")
        return out
    if isinstance(patch, FieldPatch):
        out = ["      - add_field:", f"          class: {scalar(class_ref)}", f"          name: {scalar(member)}",
               f"          type: {scalar(patch.type)}", f"          visibility: {patch.visibility}"]
        out += ["          static: true"] if patch.static else []
        out += ["          const: true"] if patch.const else []
        out += [f"          value: {_yaml_value(patch.value)}"] if patch.value is not NO_VALUE else []
        return out
    if isinstance(patch, NewMethodPatch):
        out = _add_names(patch.new_names) + ["      - add_method:", f"          class: {scalar(class_ref)}",
                                             f"          name: {scalar(patch.name or member)}",
                                             f"          visibility: {patch.visibility}"]
        out += ["          static: true"] if patch.static else []
        out += [f"          kind: {patch.kind}"] if patch.kind != "method" else []
        if patch.params:
            out.append("          params:")
            for name, written_type, default in patch.params:
                entries = ([f"name: {name}"] if name else []) + [f"type: {_flow_value(written_type)}"] + \
                    ([f"default: {_flow_value(default)}"] if default is not NO_VALUE else [])
                out.append(f"            - {{ {', '.join(entries)} }}")
        out.append(f"          returns: {scalar(patch.returns)}")
        out += [f"          locals: [{', '.join(patch.locals)}]"] if patch.locals else []
        return out + ["          code: |"] + _block(patch.code, 12)
    out = _add_names(patch.new_names) + ["      - edit:", f"          method: {scalar(patch.ref)}"]
    out += [f"          locals: [{', '.join(patch.locals)}]"] if patch.locals else []
    if isinstance(patch, MethodPatch):
        return out + ["          steps:"] + [line for step in patch.steps for line in _step_lines(step)]
    return out + ["          steps:", "            - replace:", "                match: |"] + \
        _block(patch.original, 18) + ["              with: |"] + _block(patch.code, 16)


def _step_lines(step: Step) -> list[str]:
    """An anchored step: insert (no instructions replaced) or replace, with its context patterns."""
    out = [f"            - {'replace' if step.match else 'insert'}:"]
    for part, lines in (("after", step.after), ("match", step.match), ("before", step.before)):
        if lines:
            out += [f"                {part}: |"] + _block(lines, 18)
    action = "with" if step.match else "code"
    return out + ([f"              {action}: |"] + _block(step.code, 16) if step.code else [f'              {action}: ""'])


def _add_names(new_names: list[str]) -> list[str]:
    return ["      - add_names:"] + [f"          - {scalar(name)}" for name in new_names] if new_names else []


def scalar(text: str) -> str:
    """A string as YAML writes it most plainly: bare when YAML reads it back as that same string
    (names like HubMap.<constructor> or flash.utils::Timer), quoted otherwise (*, a title with ": ")."""
    try:
        if yaml.safe_load(text) == text and text.strip() == text and "#" not in text:
            return text
    except yaml.YAMLError:
        pass
    return json.dumps(text)


def _flow_value(value: Any) -> str:
    """A value inside a { flow: mapping }: like _yaml_value, but strings quoted unless they're plain
    names (a comma or brace would end the value)."""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, str):
        return value if re.fullmatch(r"[A-Za-z_$][\w$.]*", value) and scalar(value) == value else json.dumps(value)
    return _yaml_value(value)


def _yaml_value(value: Any) -> str:
    if value is NULL or isinstance(value, bool):
        return "null" if value is NULL else ("true" if value else "false")
    if isinstance(value, float) and (value != value or value in (float("inf"), float("-inf"))):
        return "NaN" if value != value else ("Infinity" if value > 0 else "-Infinity")   # words patches accept for a Number
    return scalar(value) if isinstance(value, str) else json.dumps(value)


def _block(lines: list[str], indent: int) -> list[str]:
    return [(" " * indent + line).rstrip() for line in lines]


def kebab(ref: str) -> str:
    """A patch id from a reference: HubMap.handleScrollAndZoomTimer -> hub-map-handle-scroll-and-zoom-timer."""
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", ref.replace(".", "-"))
    return re.sub(r"[^a-z0-9]+", "-", words.lower()).strip("-")
